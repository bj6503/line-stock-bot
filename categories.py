# ----------------------------------------------------------------------
# 查詢函式
# ----------------------------------------------------------------------
def name(code):
    return META.get(code, {}).get("name", code)


def category(code):
    return META.get(code, {}).get("cat", "未分類")


def note(code):
    return META.get(code, {}).get("note", "")


def is_core(code):
    return code in CORE


def is_new_listing(code):
    return code in NEW_LISTING


def label(code):
    """給訊息用的短標籤：華城1519〔重電設備〕"""
    return "%s%s〔%s〕" % (name(code), code, category(code))


def _cat_key(cat):
    return (CAT_ORDER.index(cat), cat) if cat in CAT_ORDER else (len(CAT_ORDER), cat)


def by_category(codes=None):
    """回傳 [(類別, [代號, ...]), ...]，依 CAT_ORDER 排序。"""
    codes = WATCHLIST if codes is None else codes
    buckets = {}
    for c in codes:
        buckets.setdefault(category(c), []).append(c)
    return sorted(buckets.items(), key=lambda kv: _cat_key(kv[0]))


def format_by_category(codes=None, line_fn=None):
    """
    產生分組後的速覽文字。
    line_fn(code) 由呼叫端提供，回傳該股的一行內容（含價格、漲跌、分級等）；
    沒給的話只印名稱與代號。
    """
    if line_fn is None:
        def line_fn(c):
            return "%s %s" % (name(c), c)

    out = []
    for cat, members in by_category(codes):
        out.append("【%s】" % cat)
        for c in members:
            out.append("  " + line_fn(c))
        out.append("")
    return "\n".join(out).rstrip()


